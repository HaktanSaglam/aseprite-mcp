#Requires -Version 5.1
<#
.SYNOPSIS
  Starts the bridge in the background now and at every Windows login. No administrator rights.

.DESCRIPTION
  Writes a small launcher to %LOCALAPPDATA%\aseprite-mcp\start-bridge.ps1 and a shortcut to it
  in your Startup folder. The bridge runs hidden; its log is %LOCALAPPDATA%\aseprite-mcp\bridge.log.
  Re-running this script restarts the bridge with the current build.
  ASEPRITE_* variables and CLAUDE_PATH set while running it are copied into the launcher.
  Windows counterpart of scripts/install-service.sh (launchd / systemd).

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\install-service.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$root = Split-Path -Parent $PSScriptRoot
$bridge = Join-Path $root 'bridge'
$entry = Join-Path $bridge 'dist\index.js'
$dataDir = Join-Path $env:LOCALAPPDATA 'aseprite-mcp'
$launcher = Join-Path $dataDir 'start-bridge.ps1'
$log = Join-Path $dataDir 'bridge.log'
$shortcut = Join-Path ([Environment]::GetFolderPath('Startup')) 'Aseprite MCP bridge.lnk'
$windowsPowerShell = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'

$nodeCommand = Get-Command node -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
if (-not $nodeCommand) { throw 'node not found on PATH. Install Node.js 20+ from https://nodejs.org first.' }
$node = $nodeCommand.Source
if (-not (Get-Command claude -ErrorAction SilentlyContinue)) {
  Write-Warning "'claude' is not on PATH; the in-Aseprite chat needs Claude Code or another provider."
}

# install.ps1 has just built the bridge and sets this to skip a second build.
if ($env:ASEPRITE_MCP_SKIP_BUILD -ne '1') {
  Write-Host 'Building bridge...'
  Push-Location $bridge
  try {
    & npm.cmd run build --silent
    if ($LASTEXITCODE -ne 0) { throw "npm run build failed with exit code $LASTEXITCODE" }
  } finally {
    Pop-Location
  }
}
if (-not (Test-Path $entry)) { throw "$entry is missing. Run 'npm ci' and 'npm run build' in $bridge first." }

function ConvertTo-PsLiteral([string]$value) { "'" + $value.Replace("'", "''") + "'" }

# API keys are deliberately not copied: they belong in ~/.aseprite-mcp/config.json.
$envLines = Get-ChildItem Env: |
  Where-Object { ($_.Name -like 'ASEPRITE_*' -and $_.Name -ne 'ASEPRITE_MCP_SKIP_BUILD') -or $_.Name -eq 'CLAUDE_PATH' } |
  ForEach-Object { "`$env:$($_.Name) = $(ConvertTo-PsLiteral $_.Value)" }

New-Item -ItemType Directory -Force -Path $dataDir | Out-Null
$launcherBody = @(
  '# Generated by scripts\install-service.ps1: starts the Aseprite MCP bridge in the background.'
  '# Re-run that script after moving the repository or changing settings.'
  '$ErrorActionPreference = ''Stop'''
  $envLines
  "`$node = $(ConvertTo-PsLiteral $node)"
  "`$entry = $(ConvertTo-PsLiteral $entry)"
  "`$log = $(ConvertTo-PsLiteral $log)"
  '# Only one bridge may own the ports; replace an older one started by this launcher.'
  'Get-CimInstance Win32_Process -Filter "Name = ''node.exe''" |'
  '  Where-Object { $_.CommandLine -and $_.CommandLine.Contains($entry) } |'
  '  ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }'
  'Start-Sleep -Milliseconds 500'
  '# -NoNewWindow keeps node in this hidden console instead of opening a visible one.'
  'Start-Process -FilePath $node -ArgumentList (''"'' + $entry + ''"'') -WorkingDirectory (Split-Path -Parent (Split-Path -Parent $entry)) -NoNewWindow -RedirectStandardError $log -RedirectStandardOutput ($log + ''.out'')'
) -join "`r`n"
Set-Content -Path $launcher -Value $launcherBody -Encoding UTF8

$shell = New-Object -ComObject WScript.Shell
$link = $shell.CreateShortcut($shortcut)
$link.TargetPath = $windowsPowerShell
$link.Arguments = "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$launcher`""
$link.WorkingDirectory = $bridge
$link.WindowStyle = 7  # minimized: avoids a console flashing up at login
$link.Description = 'Starts the Aseprite MCP bridge'
$link.Save()

# Start it now the same way login will.
Start-Process -FilePath $windowsPowerShell -WindowStyle Hidden -ArgumentList @(
  '-NoProfile', '-ExecutionPolicy', 'Bypass', '-WindowStyle', 'Hidden', '-File', "`"$launcher`""
)
Start-Sleep -Seconds 3

$running = Get-CimInstance Win32_Process -Filter "Name = 'node.exe'" |
  Where-Object { $_.CommandLine -and $_.CommandLine.Contains($entry) }
if ($running) {
  Write-Host 'Bridge is running in the background and will start at every login.'
} else {
  Write-Warning "The bridge did not start; check $log"
}
Write-Host "  logs:      Get-Content -Wait `"$log`""
Write-Host "  restart:   powershell -ExecutionPolicy Bypass -File `"$launcher`""
Write-Host "  uninstall: powershell -ExecutionPolicy Bypass -File `"$root\scripts\uninstall-service.ps1`""
